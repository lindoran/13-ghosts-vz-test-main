; =============================================================================
; sdload.asm -- Benn Venn SD Loader stub for 13 Ghosts  (v3)
;
; Saved on the card as 13GHOSTS.VZ (F1 binary, start address = ORG below), so
; the loader's own  LOAD"13GHOSTS"  puts it here and jumps to it.  It then
; streams the game from several small .DAT files (13GHOST1.DAT ...), each
; opened in turn through the VZDOS file API (OpenFile / SelectHandle /
; FAT_NextSector), to the game's original addresses and starts it at vz_boot.
;
; FILE SIZE LIMIT: the real loader cannot load a file larger than 31,200 bytes
; from the SD, so NO file is ever larger than that.  make_sd.py splits the game
; into one file per segment (and further, at 60 sectors, if a segment ever
; outgrows that) and refuses to write a file over the limit.
;
; Needs VZDOS 2.32-style API (5F00 OpenFile, 5F03 SelectHandle, 5F09
; FAT_NextSector, destination pointer at FB80, 512-byte buffer at F800).
;
; Ports (as VZDOS itself uses them):  55 (37h) = memory control: bit0 selects
; SRAM (1) or the DOS EPROM (0) in 4000-67FF, bit1 = SRAM bank.  58 (3Ah) = RAM
; map (VZ200/VZ300), set by VZDOS at boot -- this stub never touches it.
; The DOS runs either from the EPROM (port 55 = 0) or, when VZDOS.VZ is on the
; card, from SRAM bank 0 (port 55 = 1).  The stub probes which at start-up and
; puts exactly that mapping back after every copy, so the DOS that is running
; stays visible for every DOS call (it never swaps in a different DOS version,
; and never overwrites the DOS).  SRAM bank 1 is switched in only around the
; copy into 4000-67FF, and stays on for the game.
;
; Everything the stub uses (code D000, staging buffer D200, stack below E400)
; sits in CA12-E411, which the game rebuilds at run time.  The segment list is
; generated by make_sd.py (sd_segments.inc).
; =============================================================================
ORG_ADDR    EQU 0D000h
STAGE       EQU 0D200h          ; 512-byte staging buffer (DOS copies one sector here)
STACK_TOP   EQU 0E400h

DOS_OPEN    EQU 05F00h
DOS_SELECT  EQU 05F03h
DOS_NEXT    EQU 05F09h
SD_DEST     EQU 0FB80h          ; DOS: destination of FAT_NextSector's copy
DOS_FOUND   EQU 0FB03h          ; DOS: 1 = file found
DOS_ERR     EQU 0FB05h          ; DOS: 1 = bad file name
RAMBUF      EQU 0F800h          ; DOS: sector buffer (holds sector 0 after SelectHandle)
PORT_MEM    EQU 037h            ; SD Loader memory control (port 55)
MEM_GAME    EQU 03h             ; SRAM selected, bank 1 in 4000-67FF = the game's 10K
PROBE       EQU 05FFFh          ; DOS-area byte used to tell EPROM from SRAM (restored)
ROM_PRINT   EQU 028A7h          ; ROM: print zero-terminated string at HL
GAME_ENTRY  EQU 0E420h          ; vz_boot
ENTRY_SIZE  EQU 15              ; dest(2) len(2) window(1) "NAME"(10)

            org ORG_ADDR

start:      di
            ld   sp, STACK_TOP
            ld   hl, PROBE           ; EPROM or SRAM in the DOS area?  Write the
            ld   b, (hl)             ; complement and read it back: SRAM keeps it,
            ld   a, b                ; the EPROM ignores the write.  The byte is
            cpl                      ; put back; no DOS code runs in between.
            ld   (hl), a
            ld   a, (hl)
            xor  b
            ld   (hl), b
            and  1
            ld   (dos_map), a        ; 1 = DOS in SRAM bank 0, 0 = DOS in EPROM
            ld   hl, segtab
            ld   (segptr), hl

nextseg:    ld   hl, (segptr)
            ld   e, (hl)
            inc  hl
            ld   d, (hl)
            inc  hl
            ld   a, d
            or   e
            jr   z, done             ; dest 0 = end of table
            ld   c, (hl)
            inc  hl
            ld   b, (hl)
            inc  hl
            ld   a, (hl)
            inc  hl                  ; HL = quoted file name
            ld   (dest), de
            ld   (len), bc
            ld   (wflag), a
            push hl
            ld   de, 10
            add  hl, de
            ld   (segptr), hl        ; next table entry
            pop  hl

            push hl                  ; the DOS reads directory/sector 0 to (FB80): after the
            ld   hl, RAMBUF          ; previous file that still points at STAGE, so put it
            ld   (SD_DEST), hl       ; back to the DOS buffer before every OpenFile
            pop  hl
            ld   a, 1
            call DOS_OPEN
            ld   a, (DOS_FOUND)
            cp   1
            jr   nz, fail
            ld   a, (DOS_ERR)
            cp   1
            jr   z, fail
            ld   a, 1
            call DOS_SELECT          ; sector 0 -> RAMBUF
            ld   a, 1
            ld   (first), a

secloop:    call getsec              ; HL = sector data
            ld   de, (dest)
            ld   bc, (len)
            ld   a, b
            cp   2
            jr   c, short            ; fewer than 512 bytes left
            ld   bc, 512
short:      push bc
            ld   a, (wflag)
            or   a
            jr   z, plain
            ld   a, MEM_GAME
            out  (PORT_MEM), a
            ldir
            ld   a, (dos_map)
            out  (PORT_MEM), a       ; the DOS that was running, visible again
            jr   copied
plain:      ldir
copied:     pop  bc
            ld   (dest), de
            ld   hl, (len)
            or   a
            sbc  hl, bc
            ld   (len), hl
            ld   a, h
            or   l
            jr   nz, secloop
            jp   nextseg

done:       di
            ld   a, MEM_GAME
            out  (PORT_MEM), a
            jp   GAME_ENTRY

fail:       ld   hl, errmsg
            call ROM_PRINT
halt_loop:  jr   halt_loop

; HL = next sector of the file (sector 0 is already in RAMBUF)
getsec:     ld   a, (first)
            or   a
            jr   z, getnext
            xor  a
            ld   (first), a
            ld   hl, RAMBUF
            ret
getnext:    ld   hl, STAGE
            ld   (SD_DEST), hl
            call DOS_NEXT
            ld   hl, STAGE
            ret

errmsg:     defb "13 GHOSTS: CAN'T OPEN GAME FILE", 0Dh, 0
first:      defb 0
dos_map:    defb 0
wflag:      defb 0
segptr:     defw 0
dest:       defw 0
len:        defw 0

            include "sd_segments.inc"
